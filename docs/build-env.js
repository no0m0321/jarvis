/**
 * Vercel build step — env.js 생성
 *
 * Vercel 환경변수에서 Supabase 키를 읽어 정적 사이트가 로드할 env.js로 출력.
 *
 * 환경변수 (Vercel Project Settings → Environment Variables 등록 필요):
 *   NEXT_PUBLIC_SUPABASE_URL       — 예: https://abcd1234.supabase.co
 *   NEXT_PUBLIC_SUPABASE_ANON_KEY  — 예: eyJhbGciOi...
 *
 * 보안:
 *   - anon key는 본래 public 설계 (RLS가 보안 레이어). 정적 site 노출 안전.
 *   - service_role key는 절대 여기 출력 금지 — 서버 함수 (api/*.ts)만.
 *
 * 사용:
 *   - 자동: vercel.json의 buildCommand가 호출 (`node build-env.js`)
 *   - 수동: 로컬에서 `NEXT_PUBLIC_SUPABASE_URL=... node build-env.js`
 */
const fs = require("fs");
const path = require("path");

const url = process.env.NEXT_PUBLIC_SUPABASE_URL || "";
const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || "";

if (!url || !key) {
  console.warn(
    "⚠ build-env: NEXT_PUBLIC_SUPABASE_URL / ANON_KEY 환경변수 누락. " +
      "env.js를 빈 placeholder로 생성합니다."
  );
}

// 가벼운 형식 검증 (실패해도 빌드는 진행)
if (url && (!url.startsWith("https://") || !url.includes(".supabase.co"))) {
  console.warn(`⚠ URL 형식 평소와 다름: ${url.slice(0, 40)}...`);
}
if (key && !key.startsWith("eyJ")) {
  console.warn(`⚠ KEY가 JWT 형식 아님 (eyJ로 시작 안 함): ${key.slice(0, 8)}...`);
}

// JSON.stringify로 안전하게 escape — 임의 string도 JS string literal로 변환
const content =
  "// Auto-generated by build-env.js — do not edit. gitignored.\n" +
  `window.SUPABASE_URL      = ${JSON.stringify(url)};\n` +
  `window.SUPABASE_ANON_KEY = ${JSON.stringify(key)};\n`;

const outPath = path.join(__dirname, "env.js");
fs.writeFileSync(outPath, content, { mode: 0o644 });

console.log(
  `OK: env.js 생성됨 (${content.length} bytes) — ` +
    `URL ${url ? "✓" : "✗"} · KEY ${key ? `✓ (${key.length}자)` : "✗"}`
);
